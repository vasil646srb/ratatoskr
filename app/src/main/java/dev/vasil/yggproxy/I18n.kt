/** [s] in the current language; with [a], a format pattern with numbered placeholders. */
fun tr(s: String, vararg a: Any?): String {
    val p = if (I18n.english) I18n.EN[s] ?: s else s
    return if (a.isEmpty()) p else String.format(Locale.ROOT, p, *a)
}
